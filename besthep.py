def euler_update(f, rates, dt):
    f_safe = np.maximum(f, 1e-30)
    log_f = np.log(f_safe)
    log_f += dt * rates / f_safe
    return np.exp(log_f)


def heun_update(f_orig, k1, k2, dt, f_pred=None):
    f0 = np.maximum(f_orig, 1e-30)
    fp = np.maximum(f_pred, 1e-30) if f_pred is not None else f0
    log_f = np.log(f0)
    log_f += dt * 0.5 * (k1 / f0 + k2 / fp)
    return np.exp(log_f)


def exprb_update(f, A, Gamma, dt):
    """Diagonal exponential Rosenbrock-Euler step for one species.

        f_new = f*exp(-Gamma*dt) + A*dt*phi1(-Gamma*dt),   phi1(z) = (e^z-1)/z

    Equivalent to f + dt*phi1(-Gamma*dt)*(A - Gamma*f). Because A >= 0, both terms
    are >= 0 for ANY sign of Gamma, so f_new >= 0 whenever f >= 0 -- no clamp on
    Gamma, no floor on f_new. Reduces to forward Euler as Gamma->0 (phi1(0)=1) and
    preserves equilibria (A - Gamma*f = 0 => f_new = f). expm1 keeps phi1 accurate
    for small z; the z=0 removable singularity uses a short Taylor branch.

    Unit-tested (pure numpy): exact (machine precision) for frozen-coefficient
    scalar linear problems, positive for both signs of Gamma; first order under
    the diagonal-Jacobian approximation (error scales with the neglected
    off-diagonal coupling). Refs: Hochbruck, Ostermann & Schweitzer (2009);
    Hochbruck & Ostermann (2010), Acta Numerica 19, eq. (2.47); diagonal/W-type
    approximation: Hairer & Wanner II, IV.7."""
    f = np.asarray(f, float); A = np.asarray(A, float); Gamma = np.asarray(Gamma, float)
    z = -Gamma * dt
    small = np.abs(z) < 1e-10
    zz = np.where(small, 1.0, z)                       # avoid 0/0 in the safe branch
    phi1 = np.where(small, 1.0 + z * (0.5 + z / 6.0), np.expm1(zz) / zz)
    return f * np.exp(z) + A * dt * phi1


def exprb2_update(f, A1, Gamma1, A2, Gamma2, dt):
    """Two-stage exponential Rosenbrock step (ETD2RK) for one species: the
    exprb_update predictor with (A1, Gamma1) of the initial state, corrected with
    (A2, Gamma2) measured at the predicted state,

        f_pred = f*exp(-Gamma1*dt) + A1*dt*phi1(-Gamma1*dt)
        f_new  = f_pred + [(A2 - A1) - (Gamma2 - Gamma1)*f_pred]*dt*phi2(-Gamma1*dt),

    phi2(z) = (phi1(z) - 1)/z. Second order in the variation of the coefficients
    over the step (exact for A linear in time and Gamma constant). In the stiff
    limit Gamma*dt >> 1 it returns the quasi-static state A/Gamma - (A/Gamma)'/Gamma
    of the moving equilibrium, where exprb_update returns A/Gamma one step late;
    the departure from equilibrium of a stiff species, which is what drives e.g.
    the source of a CP asymmetry, is therefore resolved without dt << 1/Gamma.
    The correction has either sign, so f_new is not positive by construction.
    Ref: Cox & Matthews (2002), J. Comput. Phys. 176, 430 (ETD2RK)."""
    f = np.asarray(f, float); dt = float(dt)
    A1 = np.asarray(A1, float); Gamma1 = np.asarray(Gamma1, float)
    A2 = np.asarray(A2, float); Gamma2 = np.asarray(Gamma2, float)
    z = -Gamma1 * dt
    small = np.abs(z) < 1e-4
    zz = np.where(small, 1.0, z)
    phi1 = np.where(small, 1.0 + z * (0.5 + z * (1.0 / 6.0 + z / 24.0)), np.expm1(zz) / zz)
    phi2 = np.where(small, 0.5 + z * (1.0 / 6.0 + z * (1.0 / 24.0 + z / 120.0)), (phi1 - 1.0) / zz)
    f_pred = f * np.exp(z) + A1 * dt * phi1
    return f_pred + ((A2 - A1) - (Gamma2 - Gamma1) * f_pred) * dt * phi2


def _node_weights(lg, q):
    """Linear weights in log q between the two nodes (log q values lg) around q, clamped at
    the ends: (i0, i1, w0, w1). They stand in for the derivative of the interpolated f with
    respect to its nodal values in the Jacobian of exprb_full (see collision_integrand_batch)."""
    x = np.clip(np.log(np.maximum(q, 1e-300)), lg[0], lg[-1])
    i1 = np.clip(np.searchsorted(lg, x), 1, len(lg) - 1); i0 = i1 - 1
    w1 = (x - lg[i0]) / (lg[i1] - lg[i0])
    return i0, i1, 1.0 - w1, w1


def _phi_apply(J, v, dt, k=1):
    """dt phi_k(dt J) v for k = 1, 2 (phi_1(z) = (e^z - 1)/z, phi_2 = (phi_1 - 1)/z), read off the
    exponential of the augmented matrix [[dt J, dt v, 0], [0, 0, 1], [0, 0, 0]] (k = 2; k = 1 without
    the last row and column)."""
    from scipy.linalg import expm
    n = len(v)
    M = np.zeros((n + k, n + k))
    M[:n, :n] = dt * J
    M[:n, n] = dt * v
    for i in range(k - 1):
        M[n + i, n + i + 1] = 1.0
    return expm(M)[:n, n + k - 1]


def assemble_A_Gamma(f, gain, loss, stat):
    """Per-mode (A, Gamma) for exprb_update from the OBSERVED-mode gain and loss.

        C(p) = gain - loss = G0*(1+eta*f) - L0*f = A - Gamma*f
        A     = gain / (1 + eta*f)        (= G0 >= 0, production rate)
        Gamma = loss / f - eta*A          (= L0 - eta*G0 = -dC/df, diagonal Jac)

    eta = +1 boson, -1 fermion, 0 Maxwell-Boltzmann. gain, loss are clipped to
    >= 0 against MC-noise excursions (the true integrands are positive); this only
    enforces the known sign of the rates and guarantees A >= 0 (hence positivity).
    By construction A - Gamma*f == gain - loss == net rate; evolve_step asserts
    this equals k1 to catch any per-slot mis-assignment upstream."""
    eta = 1.0 if stat == 'boson' else (-1.0 if stat == 'fermion' else 0.0)
    gain = np.maximum(np.asarray(gain, float), 0.0)
    loss = np.maximum(np.asarray(loss, float), 0.0)
    f = np.asarray(f, float)
    f_safe = np.maximum(f, 1e-300)
    A = gain / (1.0 + eta * f)
    Gamma = loss / f_safe - eta * A
    return A, Gamma


def _merge_group_states(gathered):
    """Merge the per-group (color) vegas integrators gathered from the group
    leaders into one dict for checkpointing. Inner keys carry the color
    (f"{color}_{mode}") and are disjoint, so a plain union is exact."""
    integ = {}
    for item in gathered or []:
        if item is None:
            continue
        _color, gi = item
        for proc_key, d in gi.items():
            integ.setdefault(proc_key, {}).update(d)
    return integ

def _slice_integrators_by_color(integ_all, n_groups):
    """Split a merged (all-groups) vegas-integrator dict into per-color slices
    for selective distribution at load time.

    Inner keys carry the color as f"{color}_{mode}"; the underscore terminates
    the color number, so startswith(f"{c}_") cannot cross-match (color 1 does
    not pick up "17_forward"). Colors with no entries get an empty dict --
    legacy checkpoints only ever held color 0's slice."""
    slices = {c: {} for c in range(n_groups)}
    for c in range(n_groups):
        pref = f"{c}_"
        for proc_key, d in (integ_all or {}).items():
            picked = {k: v for k, v in d.items() if k.startswith(pref)}
            if picked:
                slices[c][proc_key] = picked
    return slices

