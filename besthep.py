# Main solver
# ======================================================================
class BEST:
    """Boltzmann Equation Solver for Thermalization
    using Vegas Monte Carlo integration."""

    # Default numerical cutoffs (can be overridden per-instance)
    cutoff_zero = 1e-50
    cutoff_energy_min = 1e-50
    f_floor = 1e-300        # occupation floor applied to every initial distribution: log interpolation, all-zero detection
    f_seed = 1e-10        # amplitude of the production-spectrum seed for all-zero species
    rate_flush = 1e-150     # rate-density values below this are set to 0 before vegas: their
                            # variance underflows (x^2 < 2.2e-308, i.e. |x| < sqrt(tiny) ~ 1.5e-154)
                            # and the weighted average of the joint columns divides by it
    verbose = False         # dev/debug output
    bw_fallback_rel_err = 0.3
    def __init__(self, q_min, q_max, n_grid=500, n_r_parallel=None, max_rel_change=0.3):
        """Initialize the Boltzmann solver.

        Parameters
        ----------
        q_min, q_max : float
            Lower and upper bounds of the (comoving) momentum grid.
        n_grid : int
            Number of momentum grid points per species.
        n_r_parallel : int or None
            Number of MPI groups over which the momentum grid is split.
            The world ranks are divided into n_r_parallel groups, and the
            grid points are partitioned into that many contiguous blocks,
            one per group. Within a group, the ranks share each point's
            Vegas integration (via MPI), and the group processes the
            points in its block sequentially. Default (None) uses one
            rank per group (n_r_parallel = world_size): each rank handles
            its own block of grid points and integrates each point alone.
            A smaller value places more ranks on each integration (faster
            per point) at the cost of fewer groups (more points per group
            to process sequentially).
        max_rel_change : float
            Adaptive time-step control: the step is reduced so that the
            maximum relative change of f per step stays below this value.
            For euler/heun this is max_p |dt C[f]/f|; for 'exprb' it is the
            phi1-damped realized change max_p |dt phi1(-Gamma dt) C[f]/f|,
            so the stiff linear part no longer throttles dt.
        """

        # ---- MPI setup ----
        self.world_comm = MPI.COMM_WORLD
        self.world_rank = self.world_comm.Get_rank()
        self.world_size = self.world_comm.Get_size()

        # Default: one r-point per MPI rank (no sub-grouping)
        if n_r_parallel is None:
            n_r_parallel = self.world_size
        self.n_r_parallel = min(n_r_parallel, self.world_size)

        if self.world_size % self.n_r_parallel != 0:
            raise ValueError(f"n_r_parallel = {self.n_r_parallel} must divide the number of "
                             f"MPI ranks ({self.world_size})")
        ranks_per_group = self.world_size // self.n_r_parallel
        self.ranks_per_group = ranks_per_group

        self.color = self.world_rank // ranks_per_group
        self.sub_comm = self.world_comm.Split(self.color, self.world_rank)
        self.sub_rank = self.sub_comm.Get_rank()
        self.sub_size = self.sub_comm.Get_size()

        # Patch MPI.COMM_WORLD so vegas uses sub_comm
        import mpi4py.MPI
        mpi4py.MPI.COMM_WORLD = self.sub_comm
        import vegas
        self._vegas = vegas

        # ---- Physics ----
        self.species_config = {}   # {name: 'boson'/'fermion'}
        self.species_mass = {}     # {name: mass} (0.0 = massless)
        self.species_mass_func = {}  # {name: func(t) -> mass}
        self.q_min = q_min
        self.q_max = q_max
        self.n_grid = n_grid
        self.max_rel_change = max_rel_change

        self.distributions_1d = {}
        self.interpolators = {}
        self.r_grids = {}
        self.domain_extension = 1.5      # sampled-momentum domain / grid top

        self.process_configs = {}
        self._empty_species = set()      # species initialized at the floor: seeded at the first step
        self.vegas_integrators = {}
        self._integrator_suffix = ''
        self._analytical_integrators = {}
        self.error_stats = {'dropped': 0, 'neglected': 0, 'rel_errs': []}

        self.current_time = 0.0
        self.step_count = 0
        self.scale_factor = lambda t: 1.0  # default: no expansion
        if self.world_rank == 0:
            print(f"BEST-hep initialized")
            print(f"q_min = {q_min}, q_max = {q_max}, grid size = {n_grid}")
            print(f"MPI: {self.world_size} total ranks, "
                  f"{self.n_r_parallel} r-groups, "
                  f"{self.ranks_per_group} ranks/group")

    def set_mass_func(self, species, func):
        """Set time-dependent mass: func(t) -> mass"""
        self.species_mass_func[species] = func
        if self.world_rank == 0:
            print(f"Species {species}: time-dependent mass set")

    def set_radiation_dominated(self, a0=1.0, t0=1.0):
        self.scale_factor = lambda t, _a0=a0, _t0=t0: _a0 * (t / _t0)**0.5
        if self.current_time == 0.0:
            self.current_time = t0
        if self.world_rank == 0:
            print(f"Scale factor: radiation dominated, a0={a0}, t0={t0}")
            print(f"  current_time = {self.current_time}")
    # ------------------------------------------------------------------
    # Species energy function (supports massive particles)
    # ------------------------------------------------------------------
    def energy(self, p_vec, species=None):
        """E = sqrt(|p|^2 + m^2). p_vec is 3-vector or magnitude."""
        m = self.species_mass.get(species, 0.0) if species is not None else 0.0
        if isinstance(p_vec, (int, float)):
            return np.sqrt(p_vec**2 + m**2)
        p_sq = np.sum(np.asarray(p_vec)**2, axis=0) if np.asarray(p_vec).ndim > 1 \
            else np.asarray(p_vec)**2
        return np.sqrt(p_sq + m**2)

    # ------------------------------------------------------------------
    # Process registration
    # ------------------------------------------------------------------
    def add_process(self, name, input_species, output_species, matrix_element_squared,
                    neval=100000, nitn=2, alpha=0.5, symmetry_factor='auto'):
        """Register a process.

        matrix_element_squared(momenta): the bare |M|^2 with the couplings inside,
        summed over the internal states (spins, colours, ...) of EVERY particle,
        initial and final -- e.g. 2 y^2 (m_phi^2 - 4 m_psi^2) for phi -> psi psibar;
        the solver divides by the observed species' dof. No symmetry factors.
        momenta has shape (n_particles, 3, batch): the 3-momenta
        (px, py, pz) of the particles in the order input + output, for a batch
        of Vegas points; return one value per batch point (energies are on
        shell, E = sqrt(p^2 + m^2)).
        Energy and momentum conservation are exact for every sample: the last
        two free legs are generated by two-body kinematics (PDG, Kinematics
        review); three-leg processes (1 <-> 2) reduce to one integration variable.
        symmetry_factor: symmetry factor for identical particles multiplying |M|^2. 'auto'
        (default) is 1/(prod_s n_in,s! * prod_s n_out,s!) from the species lists;
        a number overrides it (1.0 if the function already contains the factor).
        """
        from math import factorial
        if symmetry_factor == 'auto':
            symmetry_factor = 1.0
            for s in set(input_species) | set(output_species):
                symmetry_factor /= (factorial(input_species.count(s))
                                    * factorial(output_species.count(s)))
        self.process_configs[name] = {
            'input': input_species,
            'output': output_species,
            'matrix_element_squared': matrix_element_squared,
            'symmetry_factor': float(symmetry_factor),
            'n_in': len(input_species),
            'n_out': len(output_species),
            'n_total': len(input_species) + len(output_species),
            'neval': neval,
            'nitn': nitn,
            'alpha': alpha,
        }
        for species in input_species + output_species:
            if species not in self.species_config:
                self.species_config[species] = 'boson'
                self.species_mass[species] = 0.0
        if self.world_rank == 0:
            print(f"Added process {name}: {input_species} -> {output_species} "
                  f"(neval={neval}, nitn={nitn}, "
                  f"symmetry_factor={symmetry_factor:g})")

    def set_species(self, name, stat='boson', mass=0.0, dof=1):
        """Set species statistics and mass."""
        self.species_config[name] = stat
        self.species_mass[name] = mass
        self.species_dof = getattr(self, 'species_dof', {})
        self.species_dof[name] = dof
        if self.world_rank == 0:
            print(f"Species {name}: stat={stat}, mass={mass}")

    # ------------------------------------------------------------------
    # Species initialization
    # ------------------------------------------------------------------
    def initialize_species(self, species, init_func, grid='log',
                           stat='boson', mass=0.0, dof=None):
        """Initialize species distribution on a fixed grid.
        grid: 'log' or 'linear'.
        init_func: a callable f(q), a pair of arrays (q_tab, f_tab), or the path of
        a two-column text file 'q f' ('#' comments; comma-separated if .csv), with
        q comoving at a0. Tabulated input is interpolated with the solver's own
        extrapolating interpolator. An all-zero distribution is seeded from its
        production spectrum at the first evolve_step.
        dof: internal degrees of freedom (default 2 for a fermion, 1 for a boson;
        give it explicitly for a complex scalar, a vector, ...)."""
        if species in ('times', 'a'):
            raise ValueError(f"'{species}' is a key of the history dict; use another species name")
        if isinstance(init_func, str):
            init_func = tuple(np.loadtxt(init_func, comments='#',
                                         delimiter=',' if init_func.endswith('.csv') else None).T[:2])
        if not callable(init_func):
            q_tab, f_tab = (np.asarray(x, float) for x in init_func)
            if f_tab.max() <= 0.0:              # empty table: exact floor, seeded at the first step
                init_func = lambda q: self.f_floor
            else:
                init_func = ExtrapolatingInterp(q_tab, np.clip(f_tab, self.f_floor, None), mass=mass,
                                                stat=stat, a=self.scale_factor(self.current_time))
        if dof is None:
            dof = 2 if stat == 'fermion' else 1
        self.species_dof = getattr(self, 'species_dof', {})
        self.species_dof[species] = dof
        self.species_config[species] = stat
        self.species_mass[species] = mass
        self.species_list = list(self.species_config.keys())

        if grid == 'log':
            self.r_grids[species] = np.logspace(
                np.log10(self.q_min), np.log10(self.q_max), self.n_grid)
        else:
            self.r_grids[species] = np.linspace(
                self.q_min, self.q_max, self.n_grid)

        f_values = np.maximum(np.array([init_func(r) for r in self.r_grids[species]]), self.f_floor)
        self.distributions_1d[species] = f_values
        if np.max(f_values) <= self.f_floor:
            self._empty_species.add(species)
        self.interpolators[species] = ExtrapolatingInterp(
            self.r_grids[species], f_values,
            mass=self.species_mass.get(species, 0.0),
                stat=self.species_config.get(species, 'boson'), a=self.scale_factor(self.current_time))

        if self.world_rank == 0:
            stat = self.species_config[species]
            mass = self.species_mass.get(species, 0.0)
            n = np.trapezoid(f_values * self.r_grids[species]**2,
                             self.r_grids[species]) * dof / (2 * np.pi**2)
            print(f"Initialized {species} ({stat}, m={mass}, grid={grid}): "
                  f"n = {n:.3e}")
            if mass == 0.0:
                print(f"  note: {species} is massless; its collision rates grow as 1/E towards the "
                      f"infrared (with the Bose enhancement on top for a boson), so the softest modes "
                      f"are arbitrarily stiff. A thermal mass, m proportional to 1/a, caps it.",
                      flush=True)

    def get_f(self, r, species):
        if species not in self.interpolators:
            return 0.0
        return self.interpolators[species](r)

    # ------------------------------------------------------------------
    # Vegas integrator setup
    # ------------------------------------------------------------------
    def setup_collision_integrator(self, process_name, section=None, mode='net'):
        suffix = getattr(self, '_integrator_suffix', '')
        proc_key = process_name + suffix

        if proc_key not in self.vegas_integrators:
            self.vegas_integrators[proc_key] = {}

        key = f"{section}_{mode}" if section is not None else mode
        if key not in self.vegas_integrators[proc_key]:
            config = self.process_configs[process_name]
            n_integrate = config['n_in'] + config['n_out'] - 2
            # Rotational symmetry about the target axis: the azimuth of the
            # first integrated leg is fixed at 0 (its 2*pi is folded into the
            # Jacobian), so the domain has 3*n_integrate - 1 dimensions.
            # Three legs in total (decays, inverse decays): energy conservation
            # fixes the angle of the single sampled leg, leaving one dimension,
            # the log of its energy (see collision_integrand_batch).
            domain = []
            if n_integrate == 1:
                domain = [[0.0, 1.0]]
            else:
                # n_total - 3 legs sampled freely (first azimuth fixed), the last
                # pair by two-body kinematics: two angular fractions in [0, 1]
                for k_leg in range(n_integrate - 1):
                    domain.extend([
                        [self.q_min, self.q_max * self.domain_extension], [0, np.pi]
                    ])
                    if k_leg > 0:
                        domain.append([0, 2 * np.pi])
                domain.extend([[0.0, 1.0], [0.0, 1.0]])
            if self.sub_rank == 0 and self.world_rank == 0:
                print(f"  Creating Vegas integrator for {proc_key} ({mode}) "
                      f"[group {self.color}]: {len(domain)} dimensions",
                      flush=True)
            self.vegas_integrators[proc_key][key] = \
                self._vegas.Integrator(domain, mpi=True)
        entry = self.vegas_integrators[proc_key][key]
        if not isinstance(entry, self._vegas.Integrator):
            # restored from checkpoint as AdaptiveMap: rebuild the Integrator on it
            self.vegas_integrators[proc_key][key] = self._vegas.Integrator(entry, mpi=True)
        return self.vegas_integrators[proc_key][key]

    @staticmethod
    def _two_body_window(E_t, p_t, m_t, m_s, m_c, target_alone, p_max):
        """Momentum window [p_lo, p_hi] of the sampled leg s in a three-leg
        process with the target t fixed, from the two-body kinematics.
        target_alone: t is alone on its side (parent) -- then s and c are its
        decay products and E_s = gamma (E* -/+ beta p*) in the lab;
        otherwise t and s share a side and c is the parent: the window follows
        from the invariant mass of the pair (t, s) reaching m_c at some angle.
        p_max bounds an open window from above."""
        from scipy.optimize import brentq
        if target_alone:
            E_star = (m_t**2 + m_s**2 - m_c**2) / (2.0 * m_t)
            p_star_sq = E_star**2 - m_s**2
            if p_star_sq <= 0.0:
                return None
            p_star = np.sqrt(p_star_sq)
            gamma, beta = E_t / m_t, p_t / E_t
            E_lo, E_hi = gamma * (E_star - beta * p_star), gamma * (E_star + beta * p_star)
        else:
            B = 0.5 * (m_c**2 - m_t**2 - m_s**2)
            p_of = lambda E: np.sqrt(max(E**2 - m_s**2, 0.0))
            f_lo = lambda E: E_t * E + p_t * p_of(E) - B   # antiparallel pair reaches m_c (increasing in E)
            f_hi = lambda E: E_t * E - p_t * p_of(E) - B   # parallel pair below m_c; minimum where s moves with t's velocity
            E_max = np.sqrt(p_max**2 + m_s**2)
            if f_lo(E_max) < 0.0:
                return None
            E_lo = m_s if f_lo(m_s) >= 0.0 else brentq(f_lo, m_s, E_max)
            E_v = min(m_s * E_t / m_t, E_max) if m_t > 0.0 else E_max   # massless target: f_hi decreasing
            if f_hi(E_v) > 0.0:
                return None
            E_a = m_s if f_hi(m_s) <= 0.0 else brentq(f_hi, m_s, E_v)
            E_b = E_max if f_hi(E_max) <= 0.0 else brentq(f_hi, E_v, E_max)
            E_lo, E_hi = max(E_lo, E_a), E_b
        p_lo = np.sqrt(max(E_lo**2 - m_s**2, 0.0))
        p_hi = min(np.sqrt(max(E_hi**2 - m_s**2, 0.0)), p_max)
        return (p_lo, p_hi) if p_hi > p_lo else None

    # ------------------------------------------------------------------
    # Batch collision integrand (core)
    # ------------------------------------------------------------------
    def collision_integrand_batch(self, process_name, target_species,
                                  q1_mag, mode='net', t=0.0):
        config = self.process_configs[process_name]
        input_species = config['input']
        output_species = config['output']
        all_species = input_species + output_species
        n_in = config['n_in']
        n_out = config['n_out']
        n_total = n_in + n_out


        # Place target on the side with more particles
        force = getattr(self, '_force_target_side', None)
        if force == 'input' and target_species in input_species:
            target_idx = input_species.index(target_species)
            sign = 1
        elif force == 'output' and target_species in output_species:
            target_idx = n_in + output_species.index(target_species)
            sign = -1
        elif n_out > n_in and target_species in output_species:
            target_idx = n_in + output_species.index(target_species)
            sign = -1
        elif target_species in input_species:
            target_idx = input_species.index(target_species)
            sign = 1
        else:
            target_idx = n_in + output_species.index(target_species)
            sign = -1

        stats = [self.species_config[s] for s in all_species]
        interps = {s: self.interpolators[s] for s in set(all_species)}
        matrix_element_squared = config['matrix_element_squared']
        symmetry_factor = config['symmetry_factor']
        cutoff_e = self.cutoff_energy_min
        rate_flush = self.rate_flush
        vegas_mod = self._vegas
        a = self.scale_factor(t)
        masses = [self.species_mass.get(s, 0.0) for s in all_species]
        # |M|^2 is summed over the internal states of every leg; the rate of one
        # state of the observed species is that sum divided by its own g. The
        # target's g enters again only in the moments (n = g int f).
        _dof = getattr(self, 'species_dof', {})
        g_factor = 1.0 / _dof.get(all_species[target_idx], 1)

        def _flush(y):
            # values below rate_flush are exact zeros (see the class attribute)
            y[np.abs(y) < rate_flush] = 0.0
            return y

        def _pack(FW, BW, common, f_arr=None, q_com_legs=None, wgt=None):
            if mode == 'jacobian':
                # weighted row sum_samples wgt * d(net)/d f_s(q_i), accumulated
                # outside vegas on the adapted map (see compute_collision_rate)
                acc = np.zeros(n_cols)
                _jacobian(acc, f_arr, q_com_legs, _flush(common * wgt))
                return acc
            if mode == 'joint':
                # same samples for FW and BW; vegas adapts to column 0 = FW + BW,
                # columns 1, 2 are the estimates actually used
                out = np.zeros((FW.size, 3))
                out[:, 0] = _flush((FW + BW) * common)
                out[:, 1] = _flush(FW * common)
                out[:, 2] = _flush(BW * common)
                return out
            if mode == 'forward':
                return _flush(FW * common)
            if mode == 'backward':
                return _flush(BW * common)
            return _flush((BW - FW) * common)

        eta = np.array([1.0 if st == 'boson' else (-1.0 if st == 'fermion' else 0.0) for st in stats])

        # Jacobian columns: d(net integrand)/d f_s(q_i) for every species s and
        # grid node i, laid out after the three joint columns. Column offsets per
        # species follow species_list. Used by the full-Jacobian exponential step.
        want_J = (mode == 'jacobian')
        if want_J:
            J_offset = {}
            off = 0
            for sp_ in self.species_list:
                J_offset[sp_] = off
                off += len(self.r_grids[sp_])
            n_cols = off
            logq_grid = {sp_: np.log(self.r_grids[sp_]) for sp_ in self.species_list}
            target_node = int(np.argmin(np.abs(self.r_grids[target_species] - q1_mag)))

        def _node_weights(sp_, q_com):
            """Linear weights in log q between the two neighbouring nodes (clamped
            at the ends). They stand in for the derivative of the interpolated f
            with respect to its nodal values: the exact chain factor of the
            log(1/f + eta) interpolation, f(q)(1 + eta f(q)) / (f_i (1 + eta f_i)),
            is unbounded at nodes sitting at the floor and would make the matrix
            exponential meaningless; the linear surrogate keeps J bounded and the
            exponential Rosenbrock step first-order consistent."""
            lg = logq_grid[sp_]
            x = np.clip(np.log(np.maximum(q_com, 1e-300)), lg[0], lg[-1])
            i1 = np.clip(np.searchsorted(lg, x), 1, len(lg) - 1); i0 = i1 - 1
            w1 = (x - lg[i0]) / (lg[i1] - lg[i0]); w0 = 1.0 - w1
            return i0, i1, w0, w1

        def _add_J(acc, k_leg, dval, q_com):
            """Add sum_samples wgt * d(net)/d f_leg * w_node into the nodes of leg k.
            A species outside species_list is prescribed (it does not evolve), so
            its nodes have no columns and its legs contribute nothing."""
            sp_ = all_species[k_leg]
            if sp_ not in J_offset:
                return
            i0, i1, w0, w1 = _node_weights(sp_, q_com)
            np.add.at(acc, J_offset[sp_] + i0, dval * w0)
            np.add.at(acc, J_offset[sp_] + i1, dval * w1)

        def _jacobian(acc, f_arr, q_com_legs, common):
            """Accumulate the weighted Jacobian row into `acc` (n_cols,); `common`
            already carries the sample weights. q_com_legs[k]: comoving momentum of
            leg k (None for the target: its own node, weight 1)."""
            for k in range(n_total):
                FWk = np.ones(common.size); BWk = np.ones(common.size)
                for j in range(n_total):
                    if j == k:
                        continue
                    block = 1.0 + eta[j] * f_arr[j]
                    if j < n_in:
                        FWk *= f_arr[j]; BWk *= block
                    else:
                        BWk *= f_arr[j]; FWk *= block
                # leg k enters FW (or BW) linearly and BW (or FW) through 1 + eta f
                if k < n_in:
                    dFW, dBW = FWk, eta[k] * BWk
                else:
                    dBW, dFW = BWk, eta[k] * FWk
                dnet = (dBW - dFW) * common
                if k == target_idx:
                    acc[J_offset[target_species] + target_node] += dnet.sum()
                else:
                    _add_J(acc, k, dnet, q_com_legs[k])

        def _statistics(f_arr, N):
            # FW: product of the initial-state f times the final-state (1 + eta f);
            # BW: the reverse. eta = +1 boson, -1 fermion, 0 Maxwell-Boltzmann.
            # (N explicit: an interpolator returns a float for a single sample.)
            FW = np.ones(N); BW = np.ones(N)
            for k in range(n_total):
                block = 1.0 + eta[k] * f_arr[k]
                if k < n_in:
                    FW *= f_arr[k]; BW *= block
                else:
                    BW *= f_arr[k]; FW *= block
            return FW, BW

        if n_total == 3:
            # Two-body kinematics (1 <-> 2). With the target fixed and the conserved
            # leg c from momentum conservation, energy conservation fixes the angle of
            # the one sampled leg s, so no on-shell projection is needed:
            #   d^3p_s/((2pi)^3 2E_s) d^3p_c/((2pi)^3 2E_c) (2pi)^4 delta^4 = dE_s/(8 pi p_t),
            #   C = sym |M|^2 / (16 pi g_t E_t p_t) * int dE_s [BW - FW].
            # E_s is sampled log-uniformly on its kinematic window (closed form); the
            # log map flattens the soft region where Bose factors grow as 1/E_s.
            # s: the leg on the target's side when there is one, c: the other
            others = [i for i in range(n_total) if i != target_idx]
            same = [i for i in others if (i < n_in) == (target_idx < n_in)]
            s_idx = same[0] if same else others[0]
            c_idx = [i for i in others if i != s_idx][0]
            sgn = np.array([1.0] * n_in + [-1.0] * n_out)       # +1 input side, -1 output side
            m_t, m_s, m_c = masses[target_idx], masses[s_idx], masses[c_idx]
            p_t = q1_mag / a
            E_t = np.sqrt(p_t**2 + m_t**2)
            window = self._two_body_window(
                E_t, p_t, m_t, m_s, m_c,
                target_alone=(sgn[target_idx] != sgn[s_idx] and sgn[target_idx] != sgn[c_idx]),
                p_max=self.q_max * self.domain_extension / a)
            if window is None:                                   # kinematically closed: the rate is zero
                E_lo, log_range, p_fill = m_s, 0.0, self.q_min / a
            else:
                E_lo, E_hi = (np.sqrt(window[0]**2 + m_s**2), np.sqrt(window[1]**2 + m_s**2))
                log_range, p_fill = np.log(E_hi / E_lo), window[1]
            angle_sign = sgn[target_idx] * sgn[s_idx]

            @vegas_mod.lbatchintegrand
            def integrand_two_body(x, wgt=None):
                N = x.shape[0]
                E_s = E_lo * np.exp(x[:, 0] * log_range)
                p_s = np.sqrt(np.maximum(E_s**2 - m_s**2, 0.0))
                E_c = -(sgn[target_idx] * E_t + sgn[s_idx] * E_s) / sgn[c_idx]
                valid = (E_c > m_c) & (p_s > 0.0)
                p_c = np.sqrt(np.where(valid, E_c**2 - m_c**2, 0.0))
                cos_th = np.where(valid, (p_c**2 - p_t**2 - p_s**2)
                                  / (2.0 * angle_sign * p_t * np.where(valid, p_s, 1.0)), 0.0)
                valid &= np.abs(cos_th) <= 1.0
                sin_th = np.sqrt(1.0 - np.clip(cos_th, -1.0, 1.0)**2)

                mom_x = np.zeros((n_total, N)); mom_y = np.zeros((n_total, N)); mom_z = np.zeros((n_total, N))
                mom_z[target_idx] = p_t
                mom_x[s_idx], mom_z[s_idx] = p_s * sin_th, p_s * cos_th
                for comp in (mom_x, mom_y, mom_z):
                    comp[c_idx] = -(sgn[target_idx] * comp[target_idx] + sgn[s_idx] * comp[s_idx]) / sgn[c_idx]

                # occupations at the exact momenta (comoving q = a p); invalid samples
                # are evaluated at a harmless point and get zero weight
                f_arr = [None] * n_total
                f_arr[target_idx] = np.clip(interps[all_species[target_idx]](np.full(N, q1_mag)), 0, None)
                f_arr[s_idx] = np.clip(interps[all_species[s_idx]](np.where(valid, p_s, p_fill) * a), 0, None)
                f_arr[c_idx] = np.clip(interps[all_species[c_idx]](np.where(valid, p_c, p_fill) * a), 0, None)
                FW, BW = _statistics(f_arr, N)

                M_sq = matrix_element_squared(np.stack([mom_x, mom_y, mom_z], axis=1)) * symmetry_factor
                measure = np.where(valid, E_s * log_range / (8.0 * np.pi * p_t), 0.0)   # dE_s/(8 pi p_t)
                common = sign * g_factor * M_sq * measure / (2.0 * E_t)
                q_legs = [None] * n_total
                q_legs[s_idx] = np.where(valid, p_s, p_fill) * a
                q_legs[c_idx] = np.where(valid, p_c, p_fill) * a
                return _pack(FW, BW, common, f_arr, q_legs, wgt)

            return integrand_two_body

        # Exact phase space for n_total >= 4: every free leg but two is sampled
        # freely; the remaining pair (s, c), taken on the side opposite to the
        # target when it has two free legs, is generated as the two-body decay
        # of the recoil four-momentum R = (sum of the other legs, with signs so
        # that p_s + p_c = R), in the rest frame of R and boosted back. Energy
        # conservation is then exact for every sample, there is no width
        # parameter, and the pair measure p*/(4 pi M_R) per unit solid-angle
        # fraction is smooth everywhere (no 1/|R| from a lab-frame energy
        # variable).
        free_out = [i for i in range(n_in, n_total) if i != target_idx]
        free_in = [i for i in range(n_in) if i != target_idx]
        opposite, same = (free_out, free_in) if target_idx < n_in else (free_in, free_out)
        pair = opposite if len(opposite) >= 2 else same     # fewest legs subtracted from R
        s_idx, c_idx = pair[0], pair[1]
        pair_side = 'out' if s_idx >= n_in else 'in'
        sampled = [i for i in range(n_total) if i not in (target_idx, s_idx, c_idx)]
        m_s, m_c = masses[s_idx], masses[c_idx]
        p_t = q1_mag / a
        E_t = np.sqrt(p_t**2 + masses[target_idx]**2)
        p_max = self.q_max * self.domain_extension / a
        # sign with which each leg enters R: p_s + p_c = R
        r_sign = np.array([1.0] * n_in + [-1.0] * n_out)
        if pair_side == 'in':
            r_sign = -r_sign

        @vegas_mod.lbatchintegrand
        def integrand_exact(x, wgt=None):
            N = x.shape[0]
            mom_x = np.zeros((n_total, N)); mom_y = np.zeros((n_total, N)); mom_z = np.zeros((n_total, N))
            energies = np.zeros((n_total, N))
            mom_z[target_idx] = p_t
            energies[target_idx] = E_t
            measure = np.full(N, 2.0 * np.pi)          # the azimuth fixed by rotational symmetry
            col = 0
            for k_pos, k in enumerate(sampled):
                q_mag = x[:, col]; th = x[:, col + 1]; col += 2
                if k_pos == 0:
                    ph = np.zeros(N)
                else:
                    ph = x[:, col]; col += 1
                p = q_mag / a
                E = np.sqrt(p**2 + masses[k]**2)
                mom_x[k] = p * np.sin(th) * np.cos(ph)
                mom_y[k] = p * np.sin(th) * np.sin(ph)
                mom_z[k] = p * np.cos(th)
                energies[k] = E
                measure *= q_mag**2 * np.sin(th) / (a**3 * (2.0 * np.pi)**3 * 2.0 * E)
            u_cos, u_phi = x[:, col], x[:, col + 1]

            # recoil four-momentum of the pair
            R0 = np.zeros(N); Rx = np.zeros(N); Ry = np.zeros(N); Rz = np.zeros(N)
            for k in range(n_total):
                if k in (s_idx, c_idx):
                    continue
                R0 += r_sign[k] * energies[k]
                Rx += r_sign[k] * mom_x[k]; Ry += r_sign[k] * mom_y[k]; Rz += r_sign[k] * mom_z[k]
            Rmag = np.sqrt(Rx**2 + Ry**2 + Rz**2)
            M2 = R0**2 - Rmag**2
            valid = (R0 > 0.0) & (M2 > (m_s + m_c)**2)
            MR = np.sqrt(np.where(valid, M2, 1.0))
            # two-body decay of R in its rest frame: E*, p*, uniform angles
            E_star = (MR**2 + m_s**2 - m_c**2) / (2.0 * MR)
            p_star = np.sqrt(np.maximum(E_star**2 - m_s**2, 0.0))
            cos_st = 2.0 * u_cos - 1.0
            sin_st = np.sqrt(1.0 - cos_st**2)
            phi_st = 2.0 * np.pi * u_phi
            # boost along R-hat (gamma = R0/M_R, beta = |R|/R0); a recoil at rest
            # is the limit beta -> 0 with any direction serving as the axis
            gam = np.where(valid, R0 / MR, 1.0)
            bet = np.where(valid, Rmag / np.maximum(R0, 1e-300), 0.0)
            nx = np.where(Rmag > 0.0, Rx / np.where(Rmag > 0.0, Rmag, 1.0), 0.0)
            ny = np.where(Rmag > 0.0, Ry / np.where(Rmag > 0.0, Rmag, 1.0), 0.0)
            nz = np.where(Rmag > 0.0, Rz / np.where(Rmag > 0.0, Rmag, 1.0), 1.0)
            # e1, e2 perpendicular to n
            ax = np.where(np.abs(nx) < 0.9, 1.0, 0.0); ay = 1.0 - ax; az = np.zeros(N)
            e1x = ay * nz - az * ny; e1y = az * nx - ax * nz; e1z = ax * ny - ay * nx
            e1n = np.sqrt(e1x**2 + e1y**2 + e1z**2); e1x, e1y, e1z = e1x / e1n, e1y / e1n, e1z / e1n
            e2x = ny * e1z - nz * e1y; e2y = nz * e1x - nx * e1z; e2z = nx * e1y - ny * e1x
            p_par = gam * (p_star * cos_st + bet * E_star)          # along n, boosted
            p_perp = p_star * sin_st
            E_s = gam * (E_star + bet * p_star * cos_st)
            sx = p_perp * (np.cos(phi_st) * e1x + np.sin(phi_st) * e2x) + p_par * nx
            sy = p_perp * (np.cos(phi_st) * e1y + np.sin(phi_st) * e2y) + p_par * ny
            sz = p_perp * (np.cos(phi_st) * e1z + np.sin(phi_st) * e2z) + p_par * nz
            p_s = np.sqrt(sx**2 + sy**2 + sz**2)
            E_c = R0 - E_s
            p_c_sq = np.maximum(E_c**2 - m_c**2, 0.0)
            valid &= (p_s <= p_max) & (np.sqrt(p_c_sq) <= p_max)   # inside the sampled range of momenta
            mom_x[s_idx], mom_y[s_idx], mom_z[s_idx] = sx, sy, sz
            mom_x[c_idx], mom_y[c_idx], mom_z[c_idx] = Rx - sx, Ry - sy, Rz - sz
            energies[s_idx] = E_s; energies[c_idx] = E_c
            p_c = np.sqrt(p_c_sq)
            # d Phi_2 = p*/(16 pi^2 M_R) dOmega*, dOmega* = 4 pi du dv
            measure *= np.where(valid, p_star / (4.0 * np.pi * MR), 0.0)

            # occupations at the exact comoving momenta
            f_arr = [None] * n_total
            q_legs = [None] * n_total
            f_arr[target_idx] = np.clip(interps[all_species[target_idx]](np.full(N, q1_mag)), 0, None)
            for k in sampled:
                pk = np.sqrt(mom_x[k]**2 + mom_y[k]**2 + mom_z[k]**2)
                q_legs[k] = pk * a
                f_arr[k] = np.clip(interps[all_species[k]](q_legs[k]), 0, None)
            q_legs[s_idx] = np.where(valid, p_s, p_max) * a
            q_legs[c_idx] = np.where(valid, p_c, p_max) * a
            f_arr[s_idx] = np.clip(interps[all_species[s_idx]](q_legs[s_idx]), 0, None)
            f_arr[c_idx] = np.clip(interps[all_species[c_idx]](q_legs[c_idx]), 0, None)
            FW, BW = _statistics(f_arr, N)

            M_sq = matrix_element_squared(np.stack([mom_x, mom_y, mom_z], axis=1)) * symmetry_factor
            common = sign * g_factor * M_sq * measure / (2.0 * E_t)
            bad = np.zeros(N, dtype=bool)
            for k in range(n_total):
                bad |= (energies[k] < cutoff_e)
            common[bad] = 0.0
            return _pack(FW, BW, common, f_arr, q_legs, wgt)

        return integrand_exact


    # ------------------------------------------------------------------
    # Collision rate computation
    # ------------------------------------------------------------------
    def compute_collision_rate(self, r_target, species, active_processes,
                            r_index=0, t=0.0):

        total_rate = 0.0
        total_forward = 0.0
        total_backward = 0.0
        want_J = getattr(self, '_want_jacobian', False)
        total_J = np.zeros(self._n_jacobian_cols()) if want_J else None

        for process_name in active_processes:
            config = self.process_configs[process_name]
            if species not in config['input'] + config['output']:
                continue

            section = self.color
            neval = config.get('neval', 1000)
            nitn  = config.get('nitn', 2)
            alpha = config.get('alpha', 0.5)
            key = process_name + getattr(self, '_integrator_suffix', '')

            # ---- joint pass ----
            integrator_j = self.setup_collision_integrator(process_name, section, 'joint')
            batch_j = self.collision_integrand_batch(
                process_name, species, r_target, mode='joint', t=t)
            res = integrator_j(batch_j, nitn=nitn, neval=neval, alpha=alpha)
            result_f, result_b = res[1], res[2]          # correlated gvars
            result_b_dir = None
            if want_J:
                # Jacobian row on the adapted map, accumulated in chunks so that the
                # (samples x nodes) block never exists as one array
                # random_batch runs the full sample on every rank of the group (the
                # random streams are synchronized), so the batches are split by rank
                # and summed over the group
                batch_J = self.collision_integrand_batch(
                    process_name, species, r_target, mode='jacobian', t=t)
                J_part = np.zeros(self._n_jacobian_cols())
                for b_i, (x, wgt) in enumerate(integrator_j.random_batch()):
                    if b_i % self.sub_size == self.sub_rank:
                        J_part += batch_J(x, wgt)
                J_row = np.zeros_like(J_part)
                self.sub_comm.Allreduce(J_part, J_row, op=MPI.SUM)

            # ---- fallback: BW on its own map; chosen by variance ----
            rel_b = result_b.sdev / abs(result_b.mean) if result_b.mean != 0 else np.inf
            if rel_b > self.bw_fallback_rel_err:
                integrator_b = self.setup_collision_integrator(process_name, section, 'backward')
                batch_b = self.collision_integrand_batch(
                    process_name, species, r_target, mode='backward', t=t)
                result_b_dir = integrator_b(batch_b, nitn=nitn, neval=neval, alpha=alpha)
                if result_b_dir.sdev < result_b.sdev:
                    result_b = result_b_dir
                    self.error_stats['bw_fallback'] = self.error_stats.get('bw_fallback', 0) + 1

            if self.verbose and self.world_rank == 0:
                print(f"      [{key} r={r_index}] FW={result_f}  BW_joint={res[2]}"
                      + (f"  BW_direct={result_b_dir}" if result_b_dir is not None else ""))

            # ---- quality control ----
            # A point is neglected only when both directions vanish. FW alone can be
            # exactly zero for an empty species in the input slot (f1 f2 underflows)
            # while the gain (BW) is finite: that gain must be kept.
            if result_f.mean == 0 and result_b.mean == 0:
                self.error_stats['neglected'] += 1
                continue
            if result_f.mean != 0:
                rel_f = result_f.sdev / abs(result_f.mean)
                self.error_stats.setdefault('rel_errs', []).append(rel_f)
                if rel_f > 1.0:
                    self.error_stats['dropped'] += 1
                    if self.world_rank == 0:
                        print(f"      [drop] {key} r_index={r_index} rel_err_f={rel_f:.2f}")
                    continue

            rel_b = result_b.sdev / abs(result_b.mean) if result_b.mean != 0 else np.inf
            if rel_b > 1.0:
                if abs(result_b.mean) + result_b.sdev <= abs(result_f.mean):
                    # subdominant even at +1 sigma: gain -> 0, measured loss kept
                    result_b = 0.0 * result_b
                    self.error_stats['bw_zeroed'] = self.error_stats.get('bw_zeroed', 0) + 1
                else:
                    # possibly dominant and unmeasurable: hold the mode and say so
                    self.error_stats['dropped'] += 1
                    if self.world_rank == 0:
                        print(f"      [drop] {key} r_index={r_index} "
                              f"BW unmeasurable rel_err_b={rel_b:.2f}")
                    continue

            total_rate     += result_b.mean - result_f.mean
            total_forward  += result_f.mean
            total_backward += result_b.mean
            if want_J:
                total_J += J_row

        if want_J:
            return total_rate, total_forward, total_backward, total_J
        return total_rate, total_forward, total_backward

    def _n_jacobian_cols(self):
        return sum(len(self.r_grids[sp]) for sp in self.species_list)

    # ------------------------------------------------------------------
    # Rate computation over grid (Vegas)
    # ------------------------------------------------------------------
    def _compute_rates_single_pass(self, active_processes, t=0.0,
                                    species_filter=None):
        """Compute rates for a single target side configuration.

        species_filter: if provided, only compute for these species.
        Returns (species_rates, species_forward, species_backward) where
        forward/backward are the signed reaction-direction rates (sign folded
        in via the integrand). _compute_rates_vegas turns these into physical
        per-slot gain/loss.
        """
        for s, func in self.species_mass_func.items():
            self.species_mass[s] = func(t)
        species_rates = {}
        species_forward = {}
        species_backward = {}
        compute_list = species_filter if species_filter else self.species_list
        for species in compute_list:
            t_sp = time.time()
            if self.world_rank == 0:
                stat = self.species_config[species]
                mass = self.species_mass.get(species, 0.0)
                print(f"\n  Computing C[f] for {species} "
                      f"({stat}, m={mass}, a={self.scale_factor(t):.4f}) "
                      f"via {', '.join(active_processes)}:")
                print(f"    Grid points: {len(self.r_grids[species])}", flush=True)

            n_r = len(self.r_grids[species])
            rates_local = np.zeros_like(self.r_grids[species])
            fwd_local = np.zeros_like(rates_local)
            bwd_local = np.zeros_like(rates_local)
            want_J = getattr(self, '_want_jacobian', False)
            J_local = np.zeros((n_r, self._n_jacobian_cols())) if want_J else None

            block_size = n_r // self.n_r_parallel
            remainder = n_r % self.n_r_parallel
            start_idx = self.color * block_size + min(self.color, remainder)
            end_idx = (start_idx + block_size
                       + (1 if self.color < remainder else 0))
            my_r_indices = list(range(start_idx, end_idx))
            if self.step_count % 2 == 1:
                my_r_indices = my_r_indices[::-1]

            for idx, i in enumerate(my_r_indices):
                r = self.r_grids[species][i]
                if r < self.cutoff_zero:
                    continue
                res_i = self.compute_collision_rate(
                    r, species, active_processes, r_index=i, t=t)
                rates_local[i], fwd_local[i], bwd_local[i] = res_i[:3]
                if want_J:
                    J_local[i] = res_i[3]
                if (self.sub_rank == 0
                        and (idx + 1) % max(1, len(my_r_indices) // 5) == 0):
                    elapsed = time.time() - t_sp
                    rate_calc = (idx + 1) / elapsed if elapsed > 0 else 0
                    eta = ((len(my_r_indices) - idx - 1) / rate_calc
                           if rate_calc > 0 else 0)
                    if self.world_rank == 0:
                        print(f"    [Vegas] Group {self.color}: "
                              f"{(idx+1)*100//len(my_r_indices)}% "
                              f"({idx+1}/{len(my_r_indices)}), "
                              f"ETA={eta:.0f}s", flush=True)

            if self.sub_rank != 0:
                rates_local[:] = 0.0
                fwd_local[:] = 0.0
                bwd_local[:] = 0.0
                if want_J:
                    J_local[:] = 0.0

            rates = np.zeros_like(rates_local)
            fwd = np.zeros_like(fwd_local)
            bwd = np.zeros_like(bwd_local)
            self.world_comm.Allreduce(rates_local, rates, op=MPI.SUM)
            self.world_comm.Allreduce(fwd_local, fwd, op=MPI.SUM)
            self.world_comm.Allreduce(bwd_local, bwd, op=MPI.SUM)
            species_rates[species] = rates
            species_forward[species] = fwd
            species_backward[species] = bwd
            if want_J:
                J_all = np.zeros_like(J_local)
                self.world_comm.Allreduce(J_local, J_all, op=MPI.SUM)
                self._pass_jacobian[species] = J_all

            if self.world_rank == 0:
                print(f"    [Vegas] done in {time.time()-t_sp:.1f}s, "
                      f"max|C|={np.max(np.abs(rates)):.3e}")

        return species_rates, species_forward, species_backward

    def _compute_rates_vegas(self, active_processes, t=0.0):
        """Compute collision rates with slot summation for n_in != n_out.

        Returns (species_rates, species_forward, species_backward) -- the
        ORIGINAL signature, UNCHANGED. forward/backward are the signed
        reaction-direction FW/BW sums (as before); note forward==loss and
        backward==gain ONLY when the target is input-side. Do not read physical
        gain/loss off these for a species that also appears on the output side.

        SIDE EFFECT: this method also stores the
        PHYSICAL production/destruction coefficients of the observed mode,
        aligned PER SLOT, on self.gain_rates / self.loss_rates, so that
        gain - loss == rates holds identically even when the target sits on the
        OUTPUT side (e.g. cannibal phi phi <-> phi phi phi). On the '_out' slot
        the reaction-direction BW/FW roles FLIP relative to gain/loss, and the
        per-pass kf,kb already carry sign=-1, which is undone:
            input-side slot : gain = BW (=kb),   loss = FW (=kf)
            output-side slot: gain = FW (=-kf),  loss = BW (=-kb)
        (Deriving the diagonal Jacobian from the summed forward/backward instead
        of per slot is WRONG for the output side -- it mixes the (1+eta f) and f
        powers and cannot be un-mixed.)
        """
        # Update masses at time t
        for s, func in self.species_mass_func.items():
            self.species_mass[s] = func(t)

        species_rates = {sp: np.zeros_like(self.r_grids[sp])
                         for sp in self.species_list}
        # original signed FW/BW sums (returned, backward-compatible)
        species_forward = {sp: np.zeros_like(self.r_grids[sp])
                           for sp in self.species_list}
        species_backward = {sp: np.zeros_like(self.r_grids[sp])
                            for sp in self.species_list}
        # physical per-slot-aligned gain/loss (stored on self, for 'exprb')
        species_gain = {sp: np.zeros_like(self.r_grids[sp])
                        for sp in self.species_list}
        species_loss = {sp: np.zeros_like(self.r_grids[sp])
                        for sp in self.species_list}

        # NEW: the same ledgers kept PER PROCESS. The summed fixed point
        # (A_tot/Gamma_tot) lets a stiff number-conserving process (el)
        # overwrite the slow number-changing one (ann) every step; the
        # sequential stepper needs each process's (A, Gamma) separately.
        species_gain_p = {p: {sp: np.zeros_like(self.r_grids[sp])
                              for sp in self.species_list}
                          for p in active_processes}
        species_loss_p = {p: {sp: np.zeros_like(self.r_grids[sp])
                              for sp in self.species_list}
                          for p in active_processes}
        want_J = getattr(self, '_want_jacobian', False)
        if want_J:
            n_J = self._n_jacobian_cols()
            species_J = {sp: np.zeros((len(self.r_grids[sp]), n_J)) for sp in self.species_list}
            self._pass_jacobian = {}


        for process_name in active_processes:
            config = self.process_configs[process_name]
            input_species = config['input']
            output_species = config['output']

            for species in self.species_list:
                n_in_s = input_species.count(species)
                n_out_s = output_species.count(species)

                if n_in_s == 0 and n_out_s == 0:
                    continue

                symmetric = sorted(input_species) == sorted(output_species)

                if n_in_s == n_out_s and symmetric:
                    # Symmetric process: C_in = C_out by relabeling. Compute once
                    # (target auto-placed on the input side, sign=+1), multiply by
                    # n_in_s. Input-side alignment: BW=gain, FW=loss.
                    self._force_target_side = None
                    k, kf, kb = self._compute_rates_single_pass(
                        [process_name], t=t, species_filter=[species])
                    species_rates[species]    += n_in_s * k[species]
                    if want_J:
                        species_J[species] += n_in_s * self._pass_jacobian[species]
                    species_forward[species]  += n_in_s * kf[species]   # original semantics
                    species_backward[species] += n_in_s * kb[species]
                    species_gain[species]     += n_in_s * kb[species]   # input: BW=gain
                    species_loss[species]     += n_in_s * kf[species]   #        FW=loss
                    species_gain_p[process_name][species]     += n_in_s * kb[species]
                    species_loss_p[process_name][species]     += n_in_s * kf[species]
                else:
                    # Asymmetric OR n_in_s != n_out_s: compute each side present.
                    if n_in_s > 0:
                        self._integrator_suffix = '_in'
                        self._force_target_side = 'input'
                        k_in, kf_in, kb_in = self._compute_rates_single_pass(
                            [process_name], t=t, species_filter=[species])
                        species_rates[species]    += n_in_s * k_in[species]
                        if want_J:
                            species_J[species] += n_in_s * self._pass_jacobian[species]
                        species_forward[species]  += n_in_s * kf_in[species]
                        species_backward[species] += n_in_s * kb_in[species]
                        species_gain[species]     += n_in_s * kb_in[species]  # input: BW=gain
                        species_loss[species]     += n_in_s * kf_in[species]  #        FW=loss
                        species_gain_p[process_name][species]     += n_in_s * kb_in[species]  # input: BW=gain
                        species_loss_p[process_name][species]     += n_in_s * kf_in[species]  #        FW=loss
                    if n_out_s > 0:
                        self._integrator_suffix = '_out'
                        self._force_target_side = 'output'
                        k_out, kf_out, kb_out = self._compute_rates_single_pass(
                            [process_name], t=t, species_filter=[species])
                        species_rates[species]    += n_out_s * k_out[species]
                        if want_J:
                            species_J[species] += n_out_s * self._pass_jacobian[species]
                        species_forward[species]  += n_out_s * kf_out[species]   # original semantics
                        species_backward[species] += n_out_s * kb_out[species]
                        # output-side: roles FLIP; sign=-1 folded in kf_out,kb_out -> undo
                        species_gain[species]     += n_out_s * (-kf_out[species])  # FW_out=gain
                        species_loss[species]     += n_out_s * (-kb_out[species])  # BW_out=loss
                        species_gain_p[process_name][species]     += n_out_s * (-kf_out[species])  # FW_out=gain
                        species_loss_p[process_name][species]     += n_out_s * (-kb_out[species])  # BW_out=loss

                    self._force_target_side = None
                    self._integrator_suffix = ''

        # gain/loss exposed only via self (does NOT change the return signature)
        self.gain_rates = species_gain
        self.loss_rates = species_loss
        self.gain_rates_by_process = species_gain_p
        self.loss_rates_by_process = species_loss_p
        if want_J:
            self.jacobian = species_J      # rows: target species' nodes; columns: all species' nodes
        return species_rates, species_forward, species_backward

    # ------------------------------------------------------------------
    # Rate computation (Analytical, 2->2 only)
    # ------------------------------------------------------------------
    def _compute_rates_all_species(self, process_name, n_F, M_squared=None):
        """M_squared: None reads the constant bare |M|^2 off the process' function;
        a number or a callable M_squared(t) uses that bare |M|^2 instead. The
        symmetry factor for identical particles is applied here in every case, as in the Vegas
        path."""
        config = self.process_configs[process_name]
        sym = config['symmetry_factor']
        if M_squared is None:
            probe = np.random.default_rng(0).normal(size=(config['n_total'], 3, 2))
            vals = np.asarray(config['matrix_element_squared'](probe), float)
            if vals.shape != (2,) or not np.allclose(vals, vals[0]):
                raise ValueError(f"{process_name}: the analytical 2->2 method with "
                                 "M_squared=None requires a constant |M|^2")
            M_squared = float(vals[0]) * sym
        elif callable(M_squared):
            M_bare = M_squared
            M_squared = lambda t: M_bare(t) * sym
        else:
            M_squared = float(M_squared) * sym
        input_species = config['input']
        output_species = config['output']
        species_rates = {}
        all_sp = config['input'] + config['output']
        masses = [self.species_mass.get(s, 0.0) for s in all_sp]

        for species in self.species_list:
            t_sp = time.time()
            stat = self.species_config[species]
            n_r = len(self.r_grids[species])

            if self.world_rank == 0:
                print(f"\n  Computing C[f] for {species} ({stat}):")
                print(f"    Grid points: {n_r}")

            # one state of the observed species: |M|^2 (summed over all internal
            # states) divided by its own g, as in the Vegas path
            g = self.species_dof.get(species, 1)
            if callable(M_squared):
                M_squared_species = (lambda t, M=M_squared, g=g: M(t) / g)
            else:
                M_squared_species = M_squared / g
            key = (species, M_squared)
            if key not in self._analytical_integrators:
                self._analytical_integrators[key] = \
                    CollisionIntegral2to2Analytical(
                        self.q_min, self.q_max, M_squared_species,
                        masses=masses, n_F=n_F, grid='log')
            ci = self._analytical_integrators[key]

            rates_local = np.zeros(n_r)
            my_r_indices = list(range(self.world_rank, n_r, self.world_size))

            for idx, i in enumerate(my_r_indices):
                r = self.r_grids[species][i]
                if r < self.cutoff_zero:
                    continue
                rates_local[i] = ci.compute_rate(
                    r, self.interpolators[species], stat)

                if (self.world_rank == 0
                        and (idx + 1) % max(1, len(my_r_indices) // 5) == 0):
                    elapsed = time.time() - t_sp
                    rate_calc = (idx + 1) / elapsed if elapsed > 0 else 0
                    eta = ((len(my_r_indices) - idx - 1) / rate_calc
                           if rate_calc > 0 else 0)
                    print(f"    [Analytical] "
                          f"{(idx+1)*100//len(my_r_indices)}% "
                          f"({idx+1}/{len(my_r_indices)}), "
                          f"ETA={eta:.0f}s", flush=True)

            rates = np.zeros(n_r)
            self.world_comm.Allreduce(rates_local, rates, op=MPI.SUM)
            n_in_s = input_species.count(species)
            n_out_s = output_species.count(species)
            symmetric = sorted(input_species) == sorted(output_species)
            if symmetric:
                mult = n_in_s
            else:
                mult = n_in_s + n_out_s
            species_rates[species] = mult * rates

            if self.world_rank == 0:
                print(f"    [Analytical] done in {time.time()-t_sp:.1f}s, "
                      f"max|C|={np.max(np.abs(rates)):.3e}")

        return species_rates

    # ------------------------------------------------------------------
    # Time stepping (Vegas)
    # ------------------------------------------------------------------
    def _seed_from_production(self, species):
        """Start an all-zero distribution from its production spectrum:
        f = f_seed * G(q)/max G, with G the net rate at f = 0 (pure gain, since
        the loss is proportional to f). The amplitude f_seed is arbitrary as
        long as it is negligible; results must not depend on it (check by
        changing it). COLLECTIVE: called by all ranks; rank 0 holds the result,
        which evolve_step broadcasts."""
        procs = [p for p, c in self.process_configs.items()
                 if species in c['input'] + c['output']]
        if self.world_rank == 0:
            print(f"\nSeeding {species} (initialized empty) from its production spectrum: "
                  f"rate pass via {', '.join(procs)} at t = {self.current_time:.3e}", flush=True)
        rates, _, _ = self._compute_rates_vegas(procs, t=self.current_time)
        if self.world_rank == 0:
            G = np.clip(np.asarray(rates[species], float), 0.0, None)
            if G.max() <= 0.0:
                print(f"Species {species}: no production, left empty")
                return
            self.distributions_1d[species] = self.f_seed * G / G.max()
            self.interpolators[species] = ExtrapolatingInterp(
                self.r_grids[species], self.distributions_1d[species],
                mass=self.species_mass.get(species, 0.0),
                stat=self.species_config.get(species, 'boson'), a=self.scale_factor(self.current_time))
            print(f"Species {species}: all-zero distribution seeded from its production "
                  f"spectrum (f_seed = {self.f_seed:g})")

    def evolve_step(self, dt, active_processes=None,
                    adapt_dt=True, method='heun'):
        if active_processes is None:
            active_processes = list(self.process_configs.keys())
        # Species initialized empty are seeded once from their production spectrum
        # (collective: every rank runs the rate pass).
        for s in [s for s in self.species_list if s in self._empty_species]:
            self._seed_from_production(s)
            self._empty_species.discard(s)
        self._want_jacobian = (method == 'exprb_full')
        t_step_start = time.time()
        self.error_stats = {'dropped': 0, 'neglected': 0, 'rel_errs': []}

        if self.world_rank == 0:
            print(f"\n{'=' * 60}")
            print(f"Step {self.step_count} | t = {self.current_time:.3e} "
                  f"| dt = {dt:.3e} | method = {method}")
            print(f"{'=' * 60}", flush=True)

        self.r_grids = self.world_comm.bcast(self.r_grids, root=0)
        self.distributions_1d = self.world_comm.bcast(
            self.distributions_1d, root=0)
        self.interpolators = self.world_comm.bcast(self.interpolators, root=0)

        # k1 = net rates (original 3-tuple return, unchanged). The per-slot
        # aligned gain/loss for the 'exprb' path are read from self.gain_rates /
        # self.loss_rates (set as a side effect of _compute_rates_vegas).
        k1, _fwd, _bwd = self._compute_rates_vegas(
            active_processes, t=self.current_time)

        # Assemble (A, Gamma) for exponential Rosenbrock-Euler and VERIFY the
        # per-slot gain/loss alignment. A - Gamma*f must reproduce the net rate
        # k1; if not, the slot assignment in _compute_rates_vegas is wrong (not
        # the integrator). MPI-safe: rank 0 builds an error MESSAGE (or None) and
        # broadcasts it, so ALL ranks raise together (raising on rank 0 alone
        # would hang the others at the next collective).
        A_dict, Gamma_dict = {}, {}
        if method in ('exprb', 'exprb_full'):     # exprb_full: the diagonal for the dt controller
            exprb_err = None
            if self.world_rank == 0:
                for species in self.species_list:
                    stat = self.species_config.get(species, 'boson')
                    A_dict[species], Gamma_dict[species] = assemble_A_Gamma(
                        self.distributions_1d[species], self.gain_rates[species],
                        self.loss_rates[species], stat)
                    net = (A_dict[species]
                           - Gamma_dict[species] * self.distributions_1d[species])

                    scale = np.maximum(np.abs(self.gain_rates[species]),
                                    np.abs(self.loss_rates[species]))
                    if not (np.allclose(net, k1[species], rtol=1e-6, atol=1e-30)
                            or np.all(np.abs(net - k1[species]) <= 1e-9 * np.maximum(scale, 1e-300))):
                        bad = float(np.max(np.abs(net - k1[species])))
                        exprb_err = (
                            f"exprb slot alignment broken for '{species}': "
                            f"A-Gamma*f != k1 (max diff {bad:.3e}). The per-slot "
                            f"gain/loss assignment in _compute_rates_vegas is "
                            f"wrong, not the integrator.")
                        break
            exprb_err = self.world_comm.bcast(exprb_err, root=0)
            if exprb_err is not None:
                raise AssertionError(exprb_err)

        # Adaptive dt
        dt_actual = dt
        if adapt_dt and self.world_rank == 0:
            for species in self.species_list:
                f = self.distributions_1d[species]
                f_safe = np.maximum(f, 1e-30)
                if method in ('exprb', 'exprb_full'):
                    # limit the REALIZED (phi1-damped) change, not the explicit
                    # one -> the stiff linear part no longer throttles dt
                    z = np.clip(-Gamma_dict[species] * dt, -700.0, 700.0)
                    small = np.abs(z) < 1e-10
                    zz = np.where(small, 1.0, z)
                    phi1 = np.where(small, 1.0 + z * (0.5 + z / 6.0),
                                    np.expm1(zz) / zz)
                    change = dt * phi1 * k1[species] / f_safe
                else:
                    change = dt * k1[species] / f_safe
                dlogf_max = np.max(np.abs(change))
                if dlogf_max > self.max_rel_change:
                    ratio = self.max_rel_change / dlogf_max
                    dt_actual = min(dt_actual,
                                    dt * 10**np.floor(np.log10(ratio)))
            if dt_actual < dt:
                print(f"    dt adapted: {dt:.3e} -> {dt_actual:.3e}")
        dt_actual = self.world_comm.bcast(dt_actual, root=0)

        # Time integration
        if method == 'euler':
            if self.world_rank == 0:
                for species in self.species_list:
                    self.distributions_1d[species] = euler_update(
                        self.distributions_1d[species],
                        k1[species], dt_actual)
                    self.interpolators[species] = ExtrapolatingInterp(
                self.r_grids[species], self.distributions_1d[species],
                mass=self.species_mass.get(species, 0.0),
                stat=self.species_config.get(species, 'boson'), a=self.scale_factor(self.current_time + dt_actual))

        elif method == 'heun':
            f_original = {}
            for species in self.species_list:
                f_original[species] = self.distributions_1d[species].copy()

            if self.world_rank == 0:
                for species in self.species_list:
                    self.distributions_1d[species] = euler_update(
                        self.distributions_1d[species],
                        k1[species], dt_actual)
                    self.interpolators[species] = ExtrapolatingInterp(
                self.r_grids[species], self.distributions_1d[species],
                mass=self.species_mass.get(species, 0.0),
                stat=self.species_config.get(species, 'boson'), a=self.scale_factor(self.current_time + dt_actual))

            self.distributions_1d = self.world_comm.bcast(
                self.distributions_1d, root=0)
            self.interpolators = self.world_comm.bcast(
                self.interpolators, root=0)

            if self.world_rank == 0:
                print(f"    [Heun] Computing corrector k2...")

            f_predictor = {}
            for species in self.species_list:
                f_predictor[species] = self.distributions_1d[species].copy()

            k2, _, _ = self._compute_rates_vegas(
                active_processes, t=self.current_time + dt_actual)

            if self.world_rank == 0:
                for species in self.species_list:
                    self.distributions_1d[species] = heun_update(
                        f_original[species], k1[species], k2[species],
                        dt_actual, f_pred=f_predictor[species])
                    self.interpolators[species] = ExtrapolatingInterp(
                self.r_grids[species], self.distributions_1d[species],
                mass=self.species_mass.get(species, 0.0),
                stat=self.species_config.get(species, 'boson'), a=self.scale_factor(self.current_time + dt_actual))

        elif method == 'exprb':
            # Exponential Rosenbrock-Euler (1-stage, diagonal / W-type).
            #   f_new = f*exp(-Gamma*dt) + A*dt*phi1(-Gamma*dt)
            # A, Gamma were assembled + verified (A-Gamma*f == k1) above from the
            # per-slot gain/loss. Single-stage: NO extra Vegas call (like euler).
            # No clamp, no floor -- positivity is structural (A>=0, any sign of
            # Gamma). Dropped/noisy modes have gain=loss=0 -> A=Gamma=0 -> held.
            if self.world_rank == 0:
                for species in self.species_list:
                    self.distributions_1d[species] = exprb_update(
                        self.distributions_1d[species],
                        A_dict[species], Gamma_dict[species], dt_actual)
                    self.interpolators[species] = ExtrapolatingInterp(
                self.r_grids[species], self.distributions_1d[species],
                mass=self.species_mass.get(species, 0.0),
                stat=self.species_config.get(species, 'boson'), a=self.scale_factor(self.current_time + dt_actual))

        elif method == 'exprb_full':
            # Exponential Rosenbrock-Euler with the full Jacobian of the collision
            # operator over all species and processes: f_new = f + dt phi1(dt J) C,
            # with phi1(A) c read off expm([[A, c], [0, 0]]). No splitting and no
            # diagonal approximation; nothing is imposed, so number and energy
            # conservation stay diagnostics of the rates and of the step.
            # Usable while the Monte Carlo noise of J stays harmless in the
            # exponential, dt * lambda_noise << 1 (see the max Re(dt J) line under
            # verbose); for Hubble-paced steps of a very stiff process exprb_seq,
            # which is positive and stable independently of the noise, remains the
            # method of choice.
            if self.world_rank == 0:
                from scipy.linalg import expm
                sps = self.species_list
                sizes = [len(self.r_grids[sp]) for sp in sps]
                n = sum(sizes)
                F = np.concatenate([self.distributions_1d[sp] for sp in sps])
                C = np.concatenate([k1[sp] for sp in sps])
                J = np.vstack([self.jacobian[sp] for sp in sps])
                def step(h):
                    M = np.zeros((n + 1, n + 1))
                    M[:n, :n] = h * J
                    M[:n, n] = h * C
                    return F + expm(M)[:n, n]
                F_new = step(dt_actual)
                # Negative occupations are set to the floor; the number moved by this
                # per species is reported as a diagnostic of the linearization.
                neg = F_new < 0.0
                if neg.any():
                    off = 0
                    moved = []
                    for sp, sz in zip(sps, sizes):
                        q = self.r_grids[sp]; seg = slice(off, off + sz); off += sz
                        dn = np.trapezoid(q * q * np.where(neg[seg], self.f_floor - F_new[seg], 0.0), q)
                        n_sp = np.trapezoid(q * q * F[seg], q)
                        moved.append(f"{sp} {dn / n_sp:.1e}")
                    print(f"    exprb_full: negative occupations set to the floor; number moved: "
                          + ", ".join(moved), flush=True)
                    F_new[neg] = self.f_floor
                if self.verbose:
                    lam = np.linalg.eigvals(dt_actual * J)
                    print(f"    exprb_full: max Re(dt J) = {lam.real.max():+.3e}", flush=True)
                off = 0
                for sp, sz in zip(sps, sizes):
                    self.distributions_1d[sp] = F_new[off:off + sz]
                    off += sz
                    self.interpolators[sp] = ExtrapolatingInterp(
                        self.r_grids[sp], self.distributions_1d[sp],
                        mass=self.species_mass.get(sp, 0.0),
                        stat=self.species_config.get(sp, 'boson'),
                        a=self.scale_factor(self.current_time + dt_actual))

        elif method == 'exprb_seq':
            # Sequential (Gauss-Seidel) exponential splitting: each process
            # advances the FULL dt, stiffest first; processes after the first
            # get their rates RE-COMPUTED at the updated f (one extra Vegas
            # pass per later process). Rates and the assembly f are therefore
            # always consistent, and the slow (number-changing) process is
            # evaluated on the shape the stiff one just produced.
            # MPI: mid-step rate passes are COLLECTIVE -- every rank runs the
            # same sequence (order is broadcast).
            if self.world_rank == 0:
                def _stiffness(p):
                    gamma_bulk = 0.0
                    for sp in self.species_list:
                        q = self.r_grids[sp]
                        f = self.distributions_1d[sp]
                        loss = self.loss_rates_by_process[p][sp]
                        n = np.trapezoid(f * q**2, q)
                        if n > 0:
                            gamma_bulk = max(gamma_bulk,
                                            float(np.trapezoid(loss * q**2, q) / n))
                    return gamma_bulk


                order = sorted(active_processes, key=_stiffness, reverse=True)
            else:
                order = None
            order = self.world_comm.bcast(order, root=0)
            if self.world_rank == 0 and self.verbose:
                print(f"    [GS] order: {order}")
            for i, proc in enumerate(order):
                if i > 0:
                    self.distributions_1d = self.world_comm.bcast(
                        self.distributions_1d, root=0)
                    self.interpolators = self.world_comm.bcast(
                        self.interpolators, root=0)
                    self._compute_rates_vegas([proc], t=self.current_time)
                if self.world_rank == 0:
                    for species in self.species_list:
                        stat = self.species_config.get(species, 'boson')
                        A_p, G_p = assemble_A_Gamma(
                            self.distributions_1d[species],
                            self.gain_rates_by_process[proc][species],
                            self.loss_rates_by_process[proc][species], stat)
                        self.distributions_1d[species] = exprb_update(
                            self.distributions_1d[species], A_p, G_p, dt_actual)
                    a_rebuild = self.scale_factor(
                        self.current_time + dt_actual if i == len(order) - 1
                        else self.current_time)
                    for species in self.species_list:
                        self.interpolators[species] = ExtrapolatingInterp(
                            self.r_grids[species], self.distributions_1d[species],
                            mass=self.species_mass.get(species, 0.0),
                            stat=self.species_config.get(species, 'boson'), a=a_rebuild)
        else:
            raise ValueError(
                f"unknown method '{method}' "
                f"(expected 'euler', 'heun', 'exprb', 'exprb_seq' or 'exprb_full')")

        # Broadcast final state
        self.distributions_1d = self.world_comm.bcast(
            self.distributions_1d, root=0)
        self.interpolators = self.world_comm.bcast(self.interpolators, root=0)

        self.current_time += dt_actual
        self.step_count += 1

        if self.world_rank == 0:
            print(f"\nStep completed in {time.time()-t_step_start:.1f}s")
            print(f"    Vegas errors - Dropped: "
                  f"{self.error_stats['dropped']}")
            print(f"    Vegas errors - Neglected: "
                  f"{self.error_stats['neglected']}")
            if self.verbose:
                print(f"    BW fallback: {self.error_stats.get('bw_fallback', 0)}, "
                      f"zeroed: {self.error_stats.get('bw_zeroed', 0)}")
                re = self.error_stats.get('rel_errs', [])
                if re:
                    print(f"    Max rel_err: {np.max(re):.3e}")
                    print(f"    Min rel_err: {np.min(re):.3e}")
            print(f"{'=' * 60}", flush=True)

        return k1

