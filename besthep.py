"""
BEST-hep: Boltzmann Equation Solver for Thermalization (high energy physics)

A general-purpose solver for momentum-resolved Boltzmann equations
using Vegas Monte Carlo integration. Supports arbitrary n->m processes.
Energy and momentum conservation are exact for every sample: the last two
free legs of a process are generated by two-body kinematics (PDG, Kinematics
review), so no delta function is approximated and there is no width parameter.

Usage:
    from besthep import BEST
    solver = BEST(q_min=0.1, q_max=20.0)
    solver.initialize_species('phi', my_init_func, stat='boson', mass=1.0)
    solver.add_process('my_process', ['phi','phi'], ['phi','phi','phi'],
                       my_matrix_element_squared, neval=1e5)
    # my_matrix_element_squared(momenta) returns the bare |M|^2 with the couplings
    # inside; the symmetry factor for identical particles is applied automatically.
    solver.evolve_step(dt=1.0, method='exprb')   # exponential Rosenbrock-Euler

Time-stepping methods (evolve_step, method=...):
    'euler' : explicit log-space Euler.
    'heun'  : explicit 2-stage predictor-corrector (2 Vegas passes/step).
    'exprb'   : diagonal (W-type) exponential Rosenbrock-Euler. 1 Vegas pass/step
              (like euler). Positivity-preserving; the per-mode (diagonal)
              relaxation is integrated exactly, so the per-mode rates do not
              limit dt (off-diagonal mode coupling still can). First order with
              the inexact diagonal Jacobian. Refs: Hochbruck, Ostermann &
              Schweitzer (2009), SIAM J. Numer. Anal. 47(1) 786-803; Hochbruck
              & Ostermann (2010), Acta Numerica 19, 209-286, eq. (2.47). W-type
              (inexact Jacobian): Hairer & Wanner II, IV.7.
    'exprb_seq' : sequential (Gauss-Seidel) exponential splitting over
              processes: each advances the full dt with its own diagonal
              exprb substep, stiffest first; later processes' rates are
              re-measured on the updated f (2N-1 rate passes, N processes).
              Use when a stiff number-conserving process (elastic) coexists
              with slow number-changing chemistry: summed 'exprb' phi1-damps
              the slow net by the stiff Gamma (chemistry suppressed ~
              Gamma_stiff*dt); the sequential form does not. Identical to
              'exprb' for one process. First-order splitting; use
              adapt_dt=False in stiff regimes.
    'exprb_full' : exponential Rosenbrock-Euler with the full Jacobian of the
              collision operator over all species and processes, accumulated
              on the Vegas samples. No splitting, no diagonal approximation:
              the conserved directions are carried, so a bath that a slow
              process feeds or drains follows the exchange. One extra rate
              pass per step. Usable while dt * lambda_noise << 1 (the Jacobian
              is a Monte Carlo estimate; see 'max Re(dt J)' under verbose).
"""
