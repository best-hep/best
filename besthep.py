# Interpolation with power-law / exponential extrapolation
# ======================================================================
class ExtrapolatingInterp:
    def __init__(self, r_grid, f, mass=0.0, stat='boson', a=1.0):
        self.mass, self.a = mass, a
        # eta: +1 boson, -1 fermion, 0 Maxwell-Boltzmann
        if stat == 'boson':
            self.eta = 1.0
        elif stat == 'fermion':
            self.eta = -1.0
        else:
            self.eta = 0.0

        # Energy grid: E = sqrt(q^2 + (a m)^2), comoving
        E_grid = np.sqrt(r_grid**2 + (a * mass)**2)

        # Exact form: log(1/f + eta) = a + b*E
        #   boson:  f = 1/(exp(y) - 1)
        #   fermion: f = 1/(exp(y) + 1)
        #   MB:     f = exp(-y)
        f_safe = np.maximum(f, 1e-300)
        y = np.log(1.0 / f_safe + self.eta)

        # Low-p fit
        n_low = max(10, len(r_grid) // 10)
        self.b_low, self.a_low = np.polyfit(E_grid[:n_low], y[:n_low], 1)

        # High-p fit
        n_high = n_low
        Ew, yw = E_grid[-n_high:], y[-n_high:]
        dE = Ew[None, :] - Ew[:, None]; dy = yw[None, :] - yw[:, None]
        s = dy[dE > 0] / dE[dE > 0]
        self.b_high = np.median(s)
        self.a_high = np.median(yw - self.b_high * Ew)

        # interpolate on the same axis as the grid scale (auto-detected):
        # log-spaced grid -> log(r) axis; linear grid -> r axis (unchanged).
        lr = np.log(r_grid)
        self._log_axis = (np.all(r_grid > 0)
                          and np.allclose(np.diff(lr), np.diff(lr).mean(),
                                          rtol=1e-2, atol=1e-12))

        x_grid = lr if self._log_axis else r_grid
        self._y_spline = PchipInterpolator(x_grid, y)
        self._x_lo, self._x_hi = float(x_grid[0]), float(x_grid[-1])

        self.q_min = r_grid[0]
        self.q_max = r_grid[-1]
    def _y_interp(self, xq):
        # Monotone (shape-preserving) cubic in y: a plain cubic spline rings
        # across populated<->floored boundaries (the ~690 jump in y) and
        # corrupts f by orders of magnitude. Clip guards fp round-off at the
        # grid edges; true out-of-range queries never reach here (handled by
        # the extrapolation fits in __call__).
        return self._y_spline(np.clip(xq, self._x_lo, self._x_hi))

    def _energy(self, p):
        return np.sqrt(p**2 + (self.a * self.mass)**2)

    def _f_from_y(self, y):
        y = np.clip(y, -700, 700)
        if self.eta == 0.0:
            return np.exp(-y)
        if self.eta == -1.0:  # fermion
            return 1.0 / (np.exp(y) + 1.0)
        # boson
        return np.where(y > 0, 1.0 / (np.exp(y) - 1.0 + 1e-200), 0.0)

    def _xq(self, p):
        """Map a query momentum to the interpolation axis (log if log-spaced)."""
        return np.log(p) if self._log_axis else p

    def __call__(self, p):
        if isinstance(p, (int, float)):
            if p < self.q_min:
                E = self._energy(p)
                y = self.a_low + self.b_low * E
                return max(0.0, float(self._f_from_y(np.array([y]))[0]))
            elif p > self.q_max:
                E = self._energy(p)
                y = self.a_high + self.b_high * E
                return max(0.0, float(self._f_from_y(np.array([y]))[0]))
            else:
                yq = np.array([self._y_interp(self._xq(p))])
                return float(self._f_from_y(yq)[0])

        p = np.atleast_1d(np.asarray(p, dtype=float))
        result = np.empty_like(p)

        mask_low = p < self.q_min
        mask_high = p > self.q_max
        mask_mid = ~mask_low & ~mask_high

        if np.any(mask_mid):
            result[mask_mid] = self._f_from_y(self._y_interp(self._xq(p[mask_mid])))
        if np.any(mask_low):
            E_low = self._energy(p[mask_low])
            y = self.a_low + self.b_low * E_low
            result[mask_low] = self._f_from_y(y)
        if np.any(mask_high):
            E_high = self._energy(p[mask_high])
            y = self.a_high + self.b_high * E_high
            result[mask_high] = self._f_from_y(y)

        result = np.maximum(result, 0.0)
        return float(result[0]) if result.size == 1 else result


